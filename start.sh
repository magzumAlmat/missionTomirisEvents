#!/bin/bash

# =======================================================================
# ЕДИНЫЙ СКРИПТ ЗАПУСКА КВЕСТА (EventTomiris)
# =======================================================================
# Этот скрипт последовательно:
# 1. Проверяет зависимости и .env
# 2. Генерирует QR-коды
# 3. Собирает продакшн-фронтенд (Vite build)
# 4. Запускает бэкенд Telegram-бота и сервер
# =======================================================================

set -e # Остановка при любой ошибке

echo ""
echo "🚀 [1/5] Проверка конфигурации .env..."
if [ ! -f .env ]; then
  if [ -f .env.example ]; then
    echo "⚠️ Файл .env не найден. Создаём из .env.example..."
    cp .env.example .env
  else
    echo "❌ Файл .env не найден! Создайте .env перед запуском."
    exit 1
  fi
fi

# Получаем адрес из .env или ставим дефолт
DOMAIN=$(grep -E "^VITE_API_URL=" .env | cut -d '=' -f2- | tr -d '"' | tr -d "'" || echo "http://localhost:5173")
echo "✅ Конфигурация загружена. Бэкенд адрес: $DOMAIN"

echo ""
echo "📦 [2/5] Установка зависимостей (npm install)..."
npm install --silent

echo ""
echo "🔲 [3/5] Генерация QR-кодов точек..."
npm run qr -- "$DOMAIN" || {
  echo "⚠️ Генерация QR выполнена со сгенерированным адресом."
}

echo ""
echo "🔨 [4/5] Сборка продакшн-версии фронтенда (npm run build)..."
npm run build

echo ""
echo "🤖 [5/5] Запуск бэкенда и Telegram-бота..."
echo "======================================================================="
echo "✅ ВСЕ СЕРВИСЫ УСПЕШНО СОБРАНЫ И ГОТОВЫ К РАБОТЕ!"
echo "• Бэкенд и Telegram-бот запускаются на порту 3001"
echo "• Фронтенд собран в папку dist/"
echo "======================================================================="
echo ""

# Освобождаем порт 3001, если он уже занят старым процессом
PID_ON_PORT=$(lsof -ti:3001 || true)
if [ -n "$PID_ON_PORT" ]; then
  echo "⚠️ Порт 3001 занят процессом PID $PID_ON_PORT. Перезапускаем..."
  kill -9 $PID_ON_PORT 2>/dev/null || true
  sleep 1
fi

# Если установлен PM2 (менеджер процессов на сервере) — используем его
if command -v pm2 &> /dev/null; then
  echo "🔄 Запуск через PM2..."
  pm2 restart event-tomiris-server 2>/dev/null || pm2 start ecosystem.config.cjs
  pm2 save
  echo "✅ Сервер работает в фоновом режиме через PM2!"
  pm2 status
else
  # Иначе запускаем напрямую через Node.js
  echo "▶️ Запуск Node.js сервера..."
  node server/index.js
fi
